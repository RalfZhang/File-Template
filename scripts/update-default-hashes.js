#!/usr/bin/env node
'use strict';
// Regenerates the "content fingerprints of defaults we have shipped" list in
// `src/defaultTemplateHashes.ts` by *adding* the fingerprints of the templates currently in
// `asset/templates`. Run it (`npm run hashes`) after changing any default template, and commit
// the result: the extension uses this list to tell a template a user actually customized apart
// from an untouched copy of a default that some older version left in the user's folder.
// Entries are never removed — an old fingerprint still identifies an untouched copy sitting in
// the folder of a user who has not upgraded in a while.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const repoRoot = path.resolve(__dirname, '..');
const templatesDir = path.join(repoRoot, 'asset', 'templates');
const outFile = path.join(repoRoot, 'src', 'defaultTemplateHashes.ts');

function fingerprint(buffer) {
    // Line endings are normalized first so a copy that got its CRLFs rewritten along the way
    // still matches.
    const normalized = buffer.toString('utf8').replace(/\r/g, '');
    return crypto.createHash('sha256').update(normalized, 'utf8').digest('hex');
}

// Read the fingerprints already recorded straight out of the generated source, so this works
// without a build step.
const existing = Object.create(null);
if (fs.existsSync(outFile)) {
    const previous = fs.readFileSync(outFile, 'utf8');
    const blocks = /'([^']+\.tmpl)':\s*\[([^\]]*)\]/g;
    let block;
    while ((block = blocks.exec(previous)) !== null) {
        existing[block[1]] = block[2].match(/[0-9a-f]{64}/g) || [];
    }
}

for (const name of fs.readdirSync(templatesDir).filter(n => n.endsWith('.tmpl'))) {
    const hash = fingerprint(fs.readFileSync(path.join(templatesDir, name)));
    const key = name.toLowerCase();
    existing[key] = existing[key] || [];
    if (!existing[key].includes(hash)) {
        existing[key].push(hash);
    }
}

const body = Object.keys(existing).sort().map(name => {
    const hashes = existing[name].map(h => `        '${h}'`).join(',\n');
    return `    '${name}': [\n${hashes}\n    ]`;
}).join(',\n');

fs.writeFileSync(outFile, `'use strict';
// GENERATED by \`npm run hashes\` (scripts/update-default-hashes.js) — do not edit by hand, and
// never delete entries. See that script's header for why.

export const SHIPPED_DEFAULT_HASHES: { [fileName: string]: string[] } = {
${body}
};
`);

console.log(`Wrote ${outFile}`);
